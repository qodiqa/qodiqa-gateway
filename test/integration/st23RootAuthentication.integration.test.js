'use strict';

/**
 * ST23-03 — GapScanner root authenticity, real-PostgreSQL proof.
 *
 * Real disposable database (QODIQA_PG_TEST_USER creates it and runs the migration chain into it, exactly as
 * test/integration/transparencyQueue.integration.test.js does), real qodiqa_app pool for the code under test, real
 * registrar.register()/generateRoot() signing with this test file's own transparency key store (test/support/jest.setup.js: a
 * per-file temp QODIQA_TRANSPARENCY_KEYS_PATH and test KEK, ephemeral keys never printed or persisted). Proves on
 * real rows (BIGINT seq columns, the selected `signature` column, the definer-routed entry reads) that:
 *
 *   RAI-01  a root generated by registrar.generateRoot() passes the root audit — no gap of any kind;
 *   RAI-02  a HASH-CONSISTENT FORGED root (correct chain link, entry_count and root_hash over the real stored entries,
 *           the trusted signer key id, but signed by a key this instance does not trust) is reported as a
 *           CHECKPOINT_DIVERGENCE gap with details.check === 'ROOT_SIGNATURE' / 'root_signature_invalid', while the
 *           integrity checks report nothing and the genuine root still passes.
 */
// phase 17: no .env loading — the PostgreSQL target and credentials come only from the explicit process env.
const crypto = require('crypto');
const { Client, Pool } = require('pg');

const REAL_PG = process.env.QODIQA_PG_ENABLED === 'true';
const describeOrSkip = REAL_PG ? describe : describe.skip;
const DB = `qodiqa_st23ra_test_${Date.now()}_${crypto.randomBytes(3).toString('hex')}`;
const APP_USER = process.env.QODIQA_PG_USER;
const APP_PASSWORD = process.env.QODIQA_PG_PASSWORD;
const asTest = (database) => ({
  host: process.env.QODIQA_PG_HOST || 'localhost', port: parseInt(process.env.QODIQA_PG_PORT || '5432', 10),
  database, user: process.env.QODIQA_PG_TEST_USER, password: process.env.QODIQA_PG_TEST_PASSWORD, ssl: false,
});

jest.setTimeout(120_000);

describeOrSkip('ST23-03 — GapScanner authenticates transparency roots (real disposable Postgres)', () => {
  const saved = {};
  let created = false;
  let pgPool, registrar, log, createGapScanner, verify;

  // A recording gap framework: the real one's FAIL_CLOSED policy would abort the scan on the first gap; this test
  // needs every gap the scan reports.
  const recordingScanner = () => {
    const calls = [];
    const scanner = createGapScanner({
      config: { mode: 'FULL', maxBatchSize: 100, verifyEntryHashes: true, verifyRoots: true },
      _gapFramework: {
        handleGap: async (gapType, context) => { calls.push({ gapType, details: context.details }); return { gap: { gapId: `g${calls.length}` }, blocked: false }; },
        autoResolveGap: () => false,
      },
    });
    return { scanner, calls };
  };

  beforeAll(async () => {
    if (!/^[a-z][a-z0-9_]{0,62}$/.test(DB)) throw new Error('unsafe db name');
    const m = new Client(asTest('postgres')); await m.connect();
    try { await m.query(`CREATE DATABASE "${DB}"`); created = true; } finally { await m.end(); }
    const mp = new Pool(asTest(DB));
    try { jest.resetModules(); await require('../../src/infra/postgres/migrate').runMigrations({ pool: mp }); } finally { await mp.end(); }

    for (const k of ['QODIQA_PG_ENABLED', 'QODIQA_PG_DATABASE', 'QODIQA_PG_USER', 'QODIQA_PG_PASSWORD']) saved[k] = process.env[k];
    Object.assign(process.env, { QODIQA_PG_ENABLED: 'true', QODIQA_PG_DATABASE: DB, QODIQA_PG_USER: APP_USER });
    process.env['QODIQA_PG_PASSWORD'] = APP_PASSWORD;
    jest.resetModules();
    pgPool = require('../../src/infra/postgres/pool'); pgPool.initialize();
    registrar = require('../../src/core/transparency/registrar');
    log = require('../../src/core/transparency/log');
    ({ createGapScanner } = require('../../src/core/transparency/scanner/GapScanner'));
    verify = new Pool(asTest(DB));
  });

  afterAll(async () => {
    if (verify) await verify.end().catch(() => {});
    if (pgPool) await pgPool.shutdown().catch(() => {}); // also closes the role pools (rolePools.js header)
    for (const [k, v] of Object.entries(saved)) { if (v === undefined) delete process.env[k]; else process.env[k] = v; }
    if (created) {
      const { dropTestDatabase } = require('../helpers/dropTestDatabase');
      const m = new Pool(asTest('postgres'));
      try {
        const r = await dropTestDatabase(m, DB);
        // eslint-disable-next-line no-console
        if (!r.dropped) console.warn(`[st23RootAuthentication] could not drop ${DB}: ${r.error}`);
      } finally { await m.end(); }
    }
  });

  test('RAI-01 a root generated by registrar.generateRoot() passes the root audit with no gap', async () => {
    for (let i = 0; i < 3; i++) await registrar.register({ entryType: 'SYSTEM', payload: { st23: i } });
    const genuine = await registrar.generateRoot({ generatedBy: 'st23-test' });
    expect(genuine.persisted).toBe(true);

    const { scanner, calls } = recordingScanner();
    const result = await scanner.scan('FULL');
    expect(result.success).toBe(true);
    expect(result.entriesChecked).toBe(3);
    expect(calls).toEqual([]);
  });

  test('RAI-02 a hash-consistent root signed by an untrusted key is reported; integrity reports nothing; the genuine root still passes', async () => {
    await registrar.register({ entryType: 'SYSTEM', payload: { st23: 'extra' } });
    const prev = (await verify.query('SELECT * FROM transparency_roots ORDER BY id DESC LIMIT 1')).rows[0];
    const entries = (await verify.query('SELECT id, entry_hash FROM transparency_log_entries ORDER BY id ASC')).rows;
    const seqTo = Number(entries[entries.length - 1].id);
    const forged = {
      rootId: crypto.randomUUID(), seqFrom: Number(prev.seq_to) + 1, seqTo, entryCount: entries.length,
      rootHash: log.computeRootHash(entries.map((e) => e.entry_hash)), previousRootHash: prev.root_hash,
    };
    const attacker = crypto.generateKeyPairSync('ed25519').privateKey; // in-memory only
    const signature = crypto.sign(null, log.computeRootSigningBuffer(forged), attacker).toString('base64');
    await verify.query(
      `INSERT INTO transparency_roots (root_id, seq_from, seq_to, entry_count, root_hash, previous_root_hash, signature, signer_key_id, generated_by)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8, 'forger')`,
      [forged.rootId, forged.seqFrom, forged.seqTo, forged.entryCount, forged.rootHash, forged.previousRootHash, signature, prev.signer_key_id],
    );

    const { scanner, calls } = recordingScanner();
    const result = await scanner.scan('FULL');
    expect(result.success).toBe(true);
    expect(calls.filter((c) => c.details.check !== 'ROOT_SIGNATURE')).toEqual([]);  // integrity alone passes the forgery
    expect(calls).toEqual([{
      gapType: 'CHECKPOINT_DIVERGENCE',
      details: expect.objectContaining({ check: 'ROOT_SIGNATURE', context: 'root_signature_invalid', rootId: forged.rootId, signerKeyId: prev.signer_key_id, keyStatus: 'active' }),
    }]);
  });
});
