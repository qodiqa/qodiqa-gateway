#!/usr/bin/env node
'use strict';

/**
 * generates docs/api/REFERENCE.md, a complete reference of EVERY operation of the HTTP contract (docs/api/openapi.json), grouped by tag: verb and path, summary, credential,
 * parameters, request body (property names, types, required), responses. The hand-written docs/api/overview.md remains the guided tour; this file is the exhaustive, always-current list.
 *
 *   node scripts/docs/generate-api-reference.js          write
 *   node scripts/docs/generate-api-reference.js --check  exit 1 when the committed file differs (npm run docs:api-reference:check)
 */

const fs = require('fs');
const path = require('path');

const REPO = path.join(__dirname, '..', '..');
const SPEC = path.join(REPO, 'docs', 'api', 'openapi.json');
const OUT = path.join(REPO, 'docs', 'api', 'REFERENCE.md');
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

function build(spec) {
  const resolve = (x) => { let cur = x; for (let i = 0; i < 8 && cur && cur.$ref; i++) cur = cur.$ref.split('/').slice(1).reduce((o, k) => (o ? o[k] : undefined), spec); return cur; };
  const refName = (x) => (x && x.$ref ? x.$ref.split('/').pop() : null);
  const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();
  const typeOf = (s0) => {
    const s = resolve(s0) || {};
    if (s0 && s0.$ref) return `\`${refName(s0)}\``;
    if (s.enum) return `enum(${s.enum.slice(0, 6).map(String).join(', ')}${s.enum.length > 6 ? ', ...' : ''})`;
    if (s.type === 'array') return `array of ${typeOf(s.items || {})}`;
    if (s.oneOf || s.anyOf) return (s.oneOf || s.anyOf).map(typeOf).join(' or ');
    return s.format ? `${s.type || 'any'} (${s.format})` : (s.type || 'any');
  };
  const secOf = (op) => {
    const sec = op.security !== undefined ? op.security : spec.security;
    if (!sec || sec.length === 0) return 'none (public)';
    const names = []; let anon = false;
    for (const s of sec) { const k = Object.keys(s); if (!k.length) anon = true; for (const n of k) if (!names.includes(n)) names.push(n); }
    const label = names.map((n) => ({ BearerAuth: 'operator key', SigningApiKey: 'signing key', OpsTokenHeader: 'ops token (deprecated)' }[n] || n)).join(' or ');
    return anon ? `optional (${label})` : label;
  };

  const byTag = new Map();
  for (const [p, item] of Object.entries(spec.paths)) {
    for (const m of METHODS) {
      const op = item[m]; if (!op) continue;
      const tag = (op.tags && op.tags[0]) || 'Other';
      if (!byTag.has(tag)) byTag.set(tag, []);
      byTag.get(tag).push({ p, m, op, shared: item.parameters || [] });
    }
  }
  const tags = [...byTag.keys()].sort((a, b) => a.localeCompare(b));
  const total = [...byTag.values()].reduce((n, l) => n + l.length, 0);

  const L = [];
  L.push('# HTTP API reference (generated)', '');
  L.push('<!-- GENERATED by scripts/docs/generate-api-reference.js from docs/api/openapi.json - do not edit. `npm run docs:api-reference:check` fails on drift. -->', '');
  L.push(`Every operation of the HTTP contract: **${total} operations** in ${tags.length} groups. The guided tour is [API overview](./overview.md); the machine-readable contract is [openapi.json](openapi.json).`, '');
  L.push('Credentials: *operator key* = `Authorization: Bearer ok_...`; *signing key* = `Authorization: Bearer sk_...`; *none (public)* needs no credential. Operator changes also need the MFA step-up (`X-QODIQA-OTP`) where the guided reference says so.', '');
  L.push('## Contents', '');
  for (const t of tags) L.push(`- [${t}](#${t.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/ +/g, '-')}) (${byTag.get(t).length})`);
  L.push('');
  for (const t of tags) {
    L.push(`## ${t}`, '');
    const list = byTag.get(t).sort((a, b) => (a.p === b.p ? METHODS.indexOf(a.m) - METHODS.indexOf(b.m) : a.p < b.p ? -1 : 1));
    for (const { p, m, op, shared } of list) {
      L.push(`### \`${m.toUpperCase()} ${p}\``, '');
      L.push(`**${esc(op.summary || op.operationId)}** — operation \`${op.operationId}\`${op.deprecated ? ' — **deprecated**' : ''}`, '');
      L.push(`Credential: ${secOf(op)}`, '');
      if (op.description) L.push(esc(op.description).slice(0, 600), '');
      const params = [...shared, ...(op.parameters || [])].map(resolve).filter(Boolean);
      if (params.length) {
        L.push('| parameter | in | type | required | description |', '| --- | --- | --- | --- | --- |');
        for (const x of params) L.push(`| \`${x.name}\` | ${x.in} | ${typeOf(x.schema || {})} | ${x.required ? 'yes' : 'no'} | ${esc(x.description).slice(0, 160)} |`);
        L.push('');
      }
      if (op.requestBody) {
        const rb = resolve(op.requestBody); const ct = Object.keys(rb.content || {})[0];
        const sch = ct ? rb.content[ct].schema : null;
        L.push(`Request body (\`${ct || 'none'}\`${rb.required ? ', required' : ''}): ${sch ? typeOf(sch) : ''}`, '');
        const body = sch ? resolve(sch) : null;
        if (body && body.properties) {
          const req = new Set(body.required || []);
          L.push('| property | type | required |', '| --- | --- | --- |');
          for (const [k, v] of Object.entries(body.properties).slice(0, 40)) L.push(`| \`${k}\` | ${typeOf(v)} | ${req.has(k) ? 'yes' : 'no'} |`);
          if (Object.keys(body.properties).length > 40) L.push(`| ... | ${Object.keys(body.properties).length - 40} more | |`);
          L.push('');
        }
      }
      const codes = Object.entries(op.responses || {}).sort(([a], [b]) => a.localeCompare(b));
      L.push('Responses: ' + codes.map(([c, r]) => `\`${c}\` ${esc(resolve(r)?.description || refName(r) || '')}`.trim()).join(' · '), '');
    }
  }
  return `${L.join('\n').replace(/\n{3,}/g, '\n\n')}\n`;
}

if (require.main === module) {
  const content = build(JSON.parse(fs.readFileSync(SPEC, 'utf8')));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : null;
    if (cur !== content) { console.error('DRIFT: docs/api/REFERENCE.md differs from what docs/api/openapi.json generates (run npm run docs:api-reference)'); process.exit(1); }
  } else { fs.writeFileSync(OUT, content); console.log(`wrote docs/api/REFERENCE.md (${content.length} bytes)`); }
}

module.exports = { build, OUT, SPEC };
