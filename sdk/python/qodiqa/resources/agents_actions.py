"""Agents, actions, tools, delegation, approvals - sync and async resources.

GENERATED by one template (sync classes written once, async twins derived mechanically) so the two flavours cannot drift.

* ``client.agents`` / ``client.sessions``      - admin plane (operator ``api_key``; changes need the MFA step-up, configure ``otp_provider``)
* ``client.actions`` / ``tools`` / ``delegations`` - signing key (``sign_token``)
* ``client.tool_registry`` / ``mcp_servers`` / ``approvals`` - admin plane

Refusals raise (``AuthorizationError`` with ``.reason`` such as ``TOOL_NOT_REGISTERED``, ``ACTION_POLICY_DENIED``,
``SESSION_AWAITING_APPROVAL``, ``APPROVAL_DENIED``); a tool that needs a human approval makes ``actions.authorize()`` return a
pending object - test it with :func:`is_approval_pending`.
"""

from __future__ import annotations

