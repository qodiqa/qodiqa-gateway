def _need(value: Any, name: str) -> None:
    if not isinstance(value, str) or value == "":
        raise ValidationError(f'"{name}" is required.')


def _obj(value: Any, name: str) -> None:
    if not isinstance(value, dict):
        raise ValidationError(f'"{name}" must be a JSON object.')


def _q(params: Dict[str, Any]) -> Dict[str, Any]:
    return {k: v for k, v in params.items() if v is not None}


def is_approval_pending(response: Any) -> bool:
    """True when ``authorize()`` answered 202: the tool needs a human approval before an artifact is issued."""
    return isinstance(response, dict) and response.get("status") == "pending"



