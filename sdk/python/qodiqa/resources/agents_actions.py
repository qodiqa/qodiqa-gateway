class ActionsResource(BaseResource):
    """Per-action authorisation of an agent: ``/v1/actions/*`` (signing key)."""

    def authorize(self, request: Dict[str, Any]) -> Dict[str, Any]:
        """Ask permission for ONE action; returns the action artifact (<= 60 s) or, when a human approval is needed, a pending object."""
        _need(request.get("agentId"), "request.agentId")
        _need(request.get("sessionId"), "request.sessionId")
        tool = request.get("tool") or {}
        _need(tool.get("server"), "request.tool.server")
        _need(tool.get("name"), "request.tool.name")
        _obj(request.get("args"), "request.args")
        return cast(Dict[str, Any], self._http.post("/v1/actions/authorize", request, headers=self._auth.get_sign_token_header()))

    def authorize_and_wait(self, request: Dict[str, Any], timeout_s: float = 600.0, poll_s: float = 2.0) -> Dict[str, Any]:
        """``authorize()`` that waits for a pending approval, then authorises the SAME action again with the approval."""
        first = self.authorize(request)
        if not is_approval_pending(first):
            return first
        approval_id = first["data"]["approvalId"]
        self.wait_for_approval(approval_id, timeout_s=timeout_s, poll_s=poll_s)
        again = self.authorize({**request, "approvalId": approval_id})
        if is_approval_pending(again):
            raise QodiqaTimeoutError("The approval is still pending.")
        return again

    def create_plan(self, request: Dict[str, Any]) -> Dict[str, Any]:
        _need(request.get("agentId"), "request.agentId")
        _need(request.get("sessionId"), "request.sessionId")
        if not isinstance(request.get("steps"), list) or not request["steps"]:
            raise ValidationError('"request.steps" must be a non-empty array.')
        return cast(Dict[str, Any], self._http.post("/v1/actions/plans", request, headers=self._auth.get_sign_token_header()))

    def get_approval(self, approval_id: str) -> Dict[str, Any]:
        """The requester's view of its approval request (only the identity that asked sees it)."""
        _need(approval_id, "approval_id")
        res = self._http.get(f"/v1/actions/approvals/{seg(approval_id)}", headers=self._auth.get_sign_token_header())
        return cast(Dict[str, Any], res["data"])

    def cancel_approval(self, approval_id: str, reason: Optional[str] = None) -> Dict[str, Any]:
        _need(approval_id, "approval_id")
        res = self._http.post(f"/v1/actions/approvals/{seg(approval_id)}/cancel", {"reason": reason} if reason else {}, headers=self._auth.get_sign_token_header())
        return cast(Dict[str, Any], res["data"])

    def wait_for_approval(self, approval_id: str, timeout_s: float = 600.0, poll_s: float = 2.0) -> Dict[str, Any]:
        """Poll until the request is no longer PENDING; raises ``TimeoutError`` after ``timeout_s``."""
        deadline = time.monotonic() + timeout_s
        while True:
            view = self.get_approval(approval_id)
            if view.get("status") != "PENDING":
                return view
            if time.monotonic() + poll_s > deadline:
                raise QodiqaTimeoutError(f"The approval {approval_id} is still pending after {timeout_s} s.")
            time.sleep(poll_s)


