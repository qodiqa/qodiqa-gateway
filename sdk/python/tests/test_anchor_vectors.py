"""Conformance: the SDK gives the verdict recorded in docs/protocol/vectors/audit-anchor.json (family audit-anchor) for every line.

The vectors are generated by scripts/protocol/gen-audit-vectors.js and re-derived by the Node and the pure-Python independent verifiers.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from qodiqa import anchor_statement_digest, check_anchor_line

_FILE = Path(__file__).resolve().parents[3] / "docs" / "protocol" / "vectors" / "audit-anchor.json"
_VECTORS = json.loads(_FILE.read_text(encoding="utf-8"))


def test_the_pinned_minimum_of_cases() -> None:
    assert len(_VECTORS["cases"]) >= 20


@pytest.mark.parametrize("case", _VECTORS["cases"], ids=[c["id"] for c in _VECTORS["cases"]])
def test_vector(case) -> None:
    code, rec = check_anchor_line(case["input"]["line"])
    if "expectedError" in case:
        assert (code, rec) == (case["expectedError"]["code"], None)
    else:
        assert code is None and rec is not None
        assert rec["digest"] == case["expected"]["digest"]
        assert anchor_statement_digest(rec["statement"]) == case["expected"]["digest"]
