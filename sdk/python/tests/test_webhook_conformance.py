"""QODIQA Webhook Protocol — Python SDK Conformance Test.

Loads the shared, language-neutral vector file (test-vectors/webhook-v1.json)
and verifies every vector with the real, unmodified Python SDK verifier. No
signature is generated in this file — every ``expectedSignature`` and every
``verify.signature`` value comes straight from the checked-in vector file,
which was itself generated by calling the production server's signer (see
test-vectors/README.md).

This test's only job is to catch SDK-side drift from the shared protocol
contract. Server-side drift is caught independently by
``src/core/webhooks/__tests__/webhookProtocolConformance.test.js``.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict

import pytest

from qodiqa import verify_webhook_signature
from qodiqa.exceptions import (
    ExpiredSignatureError,
    InvalidSignatureError,
    InvalidTimestampError,
    MalformedSignatureError,
    QodiqaError,
)

# ---------------------------------------------------------------------------
# Load the shared vector file
# ---------------------------------------------------------------------------

VECTORS_PATH = Path(__file__).resolve().parents[3] / "test-vectors" / "webhook-v1.json"

with open(VECTORS_PATH, "r", encoding="utf-8") as f:
    VECTOR_FILE: Dict[str, Any] = json.load(f)

VECTORS = VECTOR_FILE["vectors"]

# Canonical error-category name -> real Python SDK exception class.
ERROR_CLASS_BY_NAME = {
    "MalformedSignatureError": MalformedSignatureError,
    "InvalidTimestampError": InvalidTimestampError,
    "ExpiredSignatureError": ExpiredSignatureError,
    "InvalidSignatureError": InvalidSignatureError,
}


def _epoch_seconds(iso_timestamp: str) -> float:
    """Parse an ISO-8601 UTC timestamp (as produced by JS toISOString()) into epoch seconds."""
    normalized = iso_timestamp.replace("Z", "+00:00")
    return datetime.fromisoformat(normalized).replace(tzinfo=timezone.utc).timestamp()


# ---------------------------------------------------------------------------
# Sanity checks on the shared file itself
# ---------------------------------------------------------------------------


def test_vector_file_loads_and_is_nonempty() -> None:
    assert isinstance(VECTORS, list)
    assert len(VECTORS) > 0


def test_vector_count_metadata_matches_actual_vectors() -> None:
    positive = sum(1 for v in VECTORS if v["expectedResult"] == "valid")
    negative = sum(1 for v in VECTORS if v["expectedResult"] == "invalid")
    assert VECTOR_FILE["vectorCount"]["positive"] == positive
    assert VECTOR_FILE["vectorCount"]["negative"] == negative
    assert VECTOR_FILE["vectorCount"]["total"] == len(VECTORS)


def test_protocol_version_is_v1() -> None:
    assert VECTOR_FILE["protocolVersion"] == "v1"


# ---------------------------------------------------------------------------
# Conformance — every vector, driven entirely by the shared file
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "vector",
    VECTORS,
    ids=[v["id"] for v in VECTORS],
)
def test_vector_conformance(vector: Dict[str, Any]) -> None:
    verify = vector["verify"]
    now = _epoch_seconds(verify["verifyAt"])

    call = lambda: verify_webhook_signature(  # noqa: E731
        body=verify["body"],
        signature=verify["signature"],
        timestamp=verify["timestamp"],
        secret=verify["secrets"],
        tolerance=verify["tolerance"],
        _now=now,
    )

    if vector["expectedResult"] == "valid":
        call()  # must not raise
        return

    expected_class = ERROR_CLASS_BY_NAME[vector["expectedError"]]
    with pytest.raises(expected_class):
        call()


def test_every_negative_vector_raises_a_qodiqa_error_subclass() -> None:
    """Belt-and-suspenders: negative vectors must fail closed with a typed error, never a bare exception."""
    for vector in VECTORS:
        if vector["expectedResult"] != "invalid":
            continue
        verify = vector["verify"]
        now = _epoch_seconds(verify["verifyAt"])
        with pytest.raises(QodiqaError):
            verify_webhook_signature(
                body=verify["body"],
                signature=verify["signature"],
                timestamp=verify["timestamp"],
                secret=verify["secrets"],
                tolerance=verify["tolerance"],
                _now=now,
            )
