class TestMultipleSecrets:
    OLD_SECRET = "old_secret"
    NEW_SECRET = "new_secret"

    def test_succeeds_with_first_secret(self) -> None:
        sig = make_sig(BODY, self.OLD_SECRET)
        verify(secret=[self.NEW_SECRET, self.OLD_SECRET], signature=sig)

    def test_succeeds_with_second_secret(self) -> None:
        sig = make_sig(BODY, self.NEW_SECRET)
        verify(secret=[self.OLD_SECRET, self.NEW_SECRET], signature=sig)

    def test_fails_when_no_secret_matches(self) -> None:
        sig = make_sig(BODY, "completely_different_secret")
        with pytest.raises(InvalidSignatureError):
            verify(secret=[self.OLD_SECRET, self.NEW_SECRET], signature=sig)

    def test_single_secret_list(self) -> None:
        verify(secret=[SECRET])

    def test_empty_secret_list_raises(self) -> None:
        with pytest.raises(InvalidSignatureError):
            verify(secret=[])


# ---------------------------------------------------------------------------
# WebhookVerifier class
