"""Comprehensive tests for webhook signature verification.

The signature scheme under test is the QODIQA server's actual wire format
(``src/core/webhooks/webhookDelivery.js``): an ``X-QODIQA-Signature:
sha256=<hex>`` header, a *separate* ``X-QODIQA-Timestamp`` header carrying an
ISO-8601 UTC timestamp, and HMAC-SHA256 computed over
``f"{timestamp}.{body}"``.

``TestCrossImplementationVectors`` below uses signatures generated by
actually calling the server's own ``computeSignature()`` (via Node) rather
than duplicating the algorithm in a second, potentially-diverging Python
helper — this is what makes those specific cases a genuine interop check
rather than a self-referential fixture.
"""

from __future__ import annotations

import hashlib
import hmac
from datetime import datetime, timezone
from typing import Union

import pytest

from qodiqa import (
    DEFAULT_TOLERANCE_SECONDS,
    WebhookVerifier,
    verify_webhook_signature,
)
from qodiqa.exceptions import (
    ExpiredSignatureError,
    InvalidSignatureError,
    InvalidTimestampError,
    MalformedSignatureError,
    QodiqaError,
)

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

SECRET = "whsec_test_secret_abc123"
BODY = '{"event":"sign.created","artifactId":"art-001"}'
BODY_BYTES = BODY.encode("utf-8")

NOW_ISO = "2026-01-01T00:00:00.000Z"
NOW_EPOCH = datetime(2026, 1, 1, tzinfo=timezone.utc).timestamp()


def iso_ts(epoch: float) -> str:
    """Format a Unix epoch as the ISO-8601 UTC string Node's toISOString() produces."""
    dt = datetime.fromtimestamp(epoch, tz=timezone.utc)
    return dt.strftime("%Y-%m-%dT%H:%M:%S.") + f"{int(dt.microsecond / 1000):03d}Z"


def make_sig(body: Union[str, bytes], secret: str = SECRET, ts: str = NOW_ISO) -> str:
    """Generate a valid X-QODIQA-Signature header value (mirrors computeSignature())."""
    prefix = f"{ts}.".encode("utf-8")
    body_bytes = body.encode("utf-8") if isinstance(body, str) else body
    payload = prefix + body_bytes
    digest = hmac.new(secret.encode("utf-8"), payload, hashlib.sha256).hexdigest()
    return f"sha256={digest}"


# ---------------------------------------------------------------------------
# Helper — valid path shortcut
# ---------------------------------------------------------------------------

def verify(
    body: Union[str, bytes] = BODY,
    signature: str | None = None,
    timestamp: str = NOW_ISO,
    secret: Union[str, list] = SECRET,
    tolerance: int = DEFAULT_TOLERANCE_SECONDS,
    now: float = NOW_EPOCH,
) -> None:
    if signature is None:
        first = secret if isinstance(secret, str) else (secret[0] if secret else SECRET)
        signature = make_sig(body, first, timestamp)
    verify_webhook_signature(
        body=body,
        signature=signature,
        timestamp=timestamp,
        secret=secret,
        tolerance=tolerance,
        _now=now,
    )


# ---------------------------------------------------------------------------
# Valid signatures
# ---------------------------------------------------------------------------


class TestValidSignatures:
    def test_valid_string_body(self) -> None:
        verify(body=BODY)

    def test_valid_bytes_body(self) -> None:
        verify(body=BODY_BYTES)

    def test_valid_empty_body(self) -> None:
        verify(body="")

    def test_valid_empty_bytes_body(self) -> None:
        verify(body=b"")

    def test_valid_unicode_body(self) -> None:
        body = '{"message":"こんにちは 🌏"}'
        verify(body=body, signature=make_sig(body))

    def test_valid_binary_body(self) -> None:
        body = bytes(range(256))
        sig = make_sig(body)
        verify(body=body, signature=sig)

    def test_valid_large_body(self) -> None:
        body = "x" * 1_000_000
        verify(body=body, signature=make_sig(body))

    def test_timestamp_at_tolerance_boundary(self) -> None:
        ts = iso_ts(NOW_EPOCH - DEFAULT_TOLERANCE_SECONDS)
        verify(timestamp=ts, signature=make_sig(BODY, ts=ts))

    def test_timestamp_in_future_within_tolerance(self) -> None:
        ts = iso_ts(NOW_EPOCH + 60)
        verify(timestamp=ts, signature=make_sig(BODY, ts=ts))

    def test_uppercase_hex_signature_normalised(self) -> None:
        digest = make_sig(BODY).split("sha256=")[1].upper()
        verify(signature=f"sha256={digest}")

    def test_signature_header_with_surrounding_whitespace(self) -> None:
        # A single component's whitespace is trimmed during parsing.
        digest = make_sig(BODY).split("sha256=")[1]
        verify(signature=f"  sha256={digest}  ")

    def test_duplicate_signature_headers_folded_by_proxy(self) -> None:
        # Some proxies fold two "X-QODIQA-Signature" headers of the same name
        # into one comma-joined value; both candidates must be tried.
        correct = make_sig(BODY).split("sha256=")[1]
        wrong = "a" * 64
        verify(signature=f"sha256={wrong}, sha256={correct}")


# ---------------------------------------------------------------------------
# Invalid signatures
