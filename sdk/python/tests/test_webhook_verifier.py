class TestWebhookVerifier:
    def test_valid_signature(self) -> None:
        verifier = WebhookVerifier(SECRET)
        verifier.verify(body=BODY, signature=make_sig(BODY), timestamp=NOW_ISO, _now=NOW_EPOCH)

    def test_invalid_signature_raises(self) -> None:
        verifier = WebhookVerifier(SECRET)
        with pytest.raises(InvalidSignatureError):
            verifier.verify(
                body=BODY, signature=make_sig(BODY, "wrong"), timestamp=NOW_ISO, _now=NOW_EPOCH
            )

    def test_expired_raises(self) -> None:
        verifier = WebhookVerifier(SECRET)
        ts = iso_ts(NOW_EPOCH - DEFAULT_TOLERANCE_SECONDS - 1)
        with pytest.raises(ExpiredSignatureError):
            verifier.verify(
                body=BODY, signature=make_sig(BODY, ts=ts), timestamp=ts, _now=NOW_EPOCH
            )

    def test_custom_tolerance(self) -> None:
        verifier = WebhookVerifier(SECRET, tolerance=60)
        ts = iso_ts(NOW_EPOCH - 90)  # 90s old, outside 60s window
        with pytest.raises(ExpiredSignatureError):
            verifier.verify(
                body=BODY, signature=make_sig(BODY, ts=ts), timestamp=ts, _now=NOW_EPOCH
            )

    def test_multiple_secrets(self) -> None:
        verifier = WebhookVerifier(["new_sec", SECRET])
        verifier.verify(body=BODY, signature=make_sig(BODY), timestamp=NOW_ISO, _now=NOW_EPOCH)

    def test_empty_secret_list_raises_at_construction(self) -> None:
        with pytest.raises(InvalidSignatureError):
            WebhookVerifier([])

    def test_bytes_body(self) -> None:
        verifier = WebhookVerifier(SECRET)
        verifier.verify(
            body=BODY_BYTES, signature=make_sig(BODY_BYTES), timestamp=NOW_ISO, _now=NOW_EPOCH
        )

    def test_reusable_across_multiple_requests(self) -> None:
        verifier = WebhookVerifier(SECRET)
        for _ in range(5):
            verifier.verify(body=BODY, signature=make_sig(BODY), timestamp=NOW_ISO, _now=NOW_EPOCH)


