class TestInvalidSignatures:
    def test_wrong_secret_raises(self) -> None:
        with pytest.raises(InvalidSignatureError):
            verify(secret="wrong_secret", signature=make_sig(BODY, SECRET))

    def test_modified_payload_raises(self) -> None:
        sig = make_sig(BODY)
        with pytest.raises(InvalidSignatureError):
            verify(body=BODY + "_modified", signature=sig)

    def test_truncated_signature_raises(self) -> None:
        sig_header = make_sig(BODY)
        truncated = sig_header[:-4]
        with pytest.raises((InvalidSignatureError, MalformedSignatureError)):
            verify(signature=truncated)

    def test_all_zeros_signature_raises(self) -> None:
        zeros = "0" * 64
        with pytest.raises(InvalidSignatureError):
            verify(signature=f"sha256={zeros}")

    def test_inverted_bits_raises(self) -> None:
        correct = make_sig(BODY).split("sha256=")[1]
        flipped = format(int(correct[:2], 16) ^ 0xFF, "02x") + correct[2:]
        with pytest.raises(InvalidSignatureError):
            verify(signature=f"sha256={flipped}")


# ---------------------------------------------------------------------------
# Replay / timestamp attacks
# ---------------------------------------------------------------------------


class TestReplayProtection:
    def test_expired_timestamp_raises(self) -> None:
        ts = iso_ts(NOW_EPOCH - DEFAULT_TOLERANCE_SECONDS - 1)
        sig = make_sig(BODY, ts=ts)
        with pytest.raises(ExpiredSignatureError):
            verify(timestamp=ts, signature=sig)

    def test_far_future_timestamp_raises(self) -> None:
        ts = iso_ts(NOW_EPOCH + DEFAULT_TOLERANCE_SECONDS + 1)
        sig = make_sig(BODY, ts=ts)
        with pytest.raises(ExpiredSignatureError):
            verify(timestamp=ts, signature=sig)

    def test_modified_timestamp_header_raises(self) -> None:
        # Valid sig for NOW_ISO, but the timestamp header presented to the
        # verifier is different (still within tolerance) -> HMAC mismatch,
        # not ExpiredSignatureError, because the digest was computed with
        # NOW_ISO and the verifier will recompute against the forged one.
        correct_sig = make_sig(BODY, ts=NOW_ISO)
        forged_ts = iso_ts(NOW_EPOCH - 60)  # within 300s tolerance
        with pytest.raises(InvalidSignatureError):
            verify(timestamp=forged_ts, signature=correct_sig)

    def test_custom_tolerance_respected(self) -> None:
        ts = iso_ts(NOW_EPOCH - 60)  # 60 seconds old
        sig = make_sig(BODY, ts=ts)
        verify(timestamp=ts, signature=sig, tolerance=300)
        with pytest.raises(ExpiredSignatureError):
            verify(timestamp=ts, signature=sig, tolerance=30)

    def test_zero_tolerance_rejects_any_age(self) -> None:
        ts = iso_ts(NOW_EPOCH - 1)
        sig = make_sig(BODY, ts=ts)
        with pytest.raises(ExpiredSignatureError):
            verify(timestamp=ts, signature=sig, tolerance=0)


