class TestMalformedHeaders:
    def test_empty_signature_header_raises(self) -> None:
        with pytest.raises(MalformedSignatureError):
            verify(signature="")

    def test_whitespace_only_signature_header_raises(self) -> None:
        with pytest.raises(MalformedSignatureError):
            verify(signature="   ")

    def test_component_without_equals_raises(self) -> None:
        with pytest.raises(MalformedSignatureError):
            verify(signature="noequalssign")

    def test_non_hex_signature_raises(self) -> None:
        with pytest.raises(MalformedSignatureError):
            verify(signature="sha256=ZZZZZZZZ")

    def test_empty_sha256_value_raises(self) -> None:
        with pytest.raises(MalformedSignatureError):
            verify(signature="sha256=")

    def test_missing_timestamp_header_raises(self) -> None:
        digest = make_sig(BODY).split("sha256=")[1]
        with pytest.raises(InvalidTimestampError):
            verify(timestamp="", signature=f"sha256={digest}")

    def test_whitespace_only_timestamp_header_raises(self) -> None:
        digest = make_sig(BODY).split("sha256=")[1]
        with pytest.raises(InvalidTimestampError):
            verify(timestamp="   ", signature=f"sha256={digest}")

    def test_non_iso_timestamp_raises(self) -> None:
        digest = make_sig(BODY).split("sha256=")[1]
        with pytest.raises(InvalidTimestampError):
            verify(timestamp="1700000000", signature=f"sha256={digest}")

    def test_timestamp_missing_z_suffix_raises(self) -> None:
        digest = make_sig(BODY).split("sha256=")[1]
        with pytest.raises(InvalidTimestampError):
            verify(timestamp="2026-01-01T00:00:00.000", signature=f"sha256={digest}")

    def test_timestamp_with_invalid_calendar_date_raises(self) -> None:
        digest = make_sig(BODY).split("sha256=")[1]
        with pytest.raises(InvalidTimestampError):
            verify(timestamp="2026-13-40T00:00:00.000Z", signature=f"sha256={digest}")

    def test_unsupported_scheme_only_raises(self) -> None:
        # No sha256= component at all -> malformed, not silently accepted.
        with pytest.raises(MalformedSignatureError):
            verify(signature="sha1=deadbeef")


