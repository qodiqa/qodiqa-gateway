"""Conformance: the SDK verifier gives the verdict recorded in docs/protocol/vectors/receipt.json (family v2-receipt) for every case.

The vectors are generated by scripts/protocol/gen-receipt-vectors.js and re-derived by the Node and the pure-Python independent verifiers.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from qodiqa import verify_receipt

_FILE = Path(__file__).resolve().parents[3] / "docs" / "protocol" / "vectors" / "receipt.json"
_VECTORS = json.loads(_FILE.read_text(encoding="utf-8"))
_KEYS = [
    {"keyId": k["keyId"], "publicKey": k["publicKeySpkiB64"], "status": k["status"], **({"revokedAt": k["revokedAt"]} if "revokedAt" in k else {})}
    for k in _VECTORS["keys"]
]


def test_the_pinned_minimum_of_cases() -> None:
    assert len(_VECTORS["cases"]) >= 48


@pytest.mark.parametrize("case", _VECTORS["cases"], ids=[c["id"] for c in _VECTORS["cases"]])
def test_vector(case) -> None:
    trusted_at = case["input"].get("trustedAt")
    got = verify_receipt(case["input"]["receipt"], _KEYS, trusted_at=trusted_at)
    if "expectedError" in case:
        assert got == (False, case["expectedError"]["code"]), case["description"]
    else:
        assert got == (True, None), case["description"]
