'use strict';

/**
 * End-user AI disclosure —.
 *
 * Every EXECUTE response from /ai/chat carries
 *   aiDisclosure: { aiGenerated: true, provider, model, notice }
 * plus the header  X-QODIQA-AI-Generated: true,  and the SSE stream_started
 * event carries the same aiDisclosure. BLOCK responses carry none (no AI output).
 *
 * `notice` is the tenant's published wording (tenant semantic config
 * `disclosureNotice`, set through the governed publish path) or the
 * platform default below. Integrators display it to the end user; the header
 * lets proxies and log pipelines detect AI output without parsing bodies.
 */

const tenantSemanticRegistry = require('../tenancy/tenantSemanticRegistry');

const HEADER = 'X-QODIQA-AI-Generated';
const DEFAULT_NOTICE = 'This response was generated by an AI system.';

function buildAiDisclosure({ tenantId = null, provider = null, model = null } = {}) {
  let notice = null;
  try { notice = tenantSemanticRegistry.getDisclosureNotice(tenantId); } catch { /* default below */ }
  return { aiGenerated: true, provider: provider || null, model: model || null, notice: notice || DEFAULT_NOTICE };
}

module.exports = { buildAiDisclosure, HEADER, DEFAULT_NOTICE };
