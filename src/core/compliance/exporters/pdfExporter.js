'use strict';

/**
 * PDF Exporter — auditor-friendly compliance report using pdfkit
 *
 * Produces a professional PDF document including:
 *   - Cover page with framework logo area, verdict, and metadata
 *   - Executive summary
 *   - Controls assessment table
 *   - Findings and recommendations
 *   - Evidence summary
 *   - Signature/integrity section
 *
 * pdfkit is already a declared dependency in package.json.
 */

const PDFDocument = require('pdfkit');

// ── Color palette ─────────────────────────────────────────────────────────────
const C = {
  QODIQA_BLUE:   '#0969da',
  PASS:          '#1a7f37',
  FAIL:          '#cf222e',
  PARTIAL:       '#9a6700',
  NA:            '#656d76',
  BG_LIGHT:      '#f6f8fa',
  BORDER:        '#d0d7de',
  TEXT:          '#24292f',
  TEXT_MUTED:    '#57606a',
  WHITE:         '#ffffff',
};

const VERDICT_COLOR = {
  COMPLIANT:            C.PASS,
  PARTIALLY_COMPLIANT:  C.PARTIAL,
  NON_COMPLIANT:        C.FAIL,
};

const STATUS_COLOR = {
  PASS:    C.PASS,
  PARTIAL: C.PARTIAL,
  FAIL:    C.FAIL,
  NOT_APPLICABLE: C.NA,
  ERROR:   C.FAIL,
};

// ── Helpers ───────────────────────────────────────────────────────────────────

function _safe(val) {
  return val == null ? '' : String(val);
}

function _verdictLabel(v) {
  return { COMPLIANT: 'COMPLIANT', PARTIALLY_COMPLIANT: 'PARTIALLY COMPLIANT', NON_COMPLIANT: 'NON-COMPLIANT' }[v] ?? v;
}

// ── PDF generation ────────────────────────────────────────────────────────────

/**
 * Generate a PDF buffer from a compliance report object.
 * @param {object} report  Full compliance report from reportGenerator.generateReport()
 * @returns {Promise<Buffer>}
 */
function exportPdf(report) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    const doc    = new PDFDocument({ size: 'A4', margin: 50, info: {
      Title:    `${_safe(report.framework?.name)} Compliance Report`,
      Author:   'QODIQA Compliance Reporting Framework',
      Subject:  `${_safe(report.framework?.name)} Assessment — ${_safe(report.reportRef)}`,
      Creator:  'QODIQA v' + _safe(report.generatorVersion),
    }});

    doc.on('data',  chunk => chunks.push(chunk));
    doc.on('end',   ()    => resolve(Buffer.concat(chunks)));
    doc.on('error', err   => reject(err));

    _renderCover(doc, report);
    _renderExecutiveSummary(doc, report);
    _renderControlsTable(doc, report);
    _renderFindings(doc, report);
    _renderEvidenceSummary(doc, report);
    _renderRecommendations(doc, report);
    _renderSignature(doc, report);
    _renderFooter(doc, report);

    doc.end();
  });
}

// ── Cover page ────────────────────────────────────────────────────────────────

function _renderCover(doc, report) {
  const fw      = report.framework ?? {};
  const verdict = report.overallVerdict ?? 'NON_COMPLIANT';
  const score   = report.overallScore ?? 0;

  // Header band
  doc.rect(0, 0, doc.page.width, 120).fill(C.QODIQA_BLUE);
  doc.fillColor(C.WHITE).fontSize(22).font('Helvetica-Bold')
     .text('QODIQA', 50, 30, { continued: true })
     .font('Helvetica').fontSize(14).text(' Compliance Report', { continued: false });

  doc.fontSize(10).text('Deterministic Runtime Consent Enforcement', 50, 58, { color: '#a8d8ff' });

  // Framework name
  doc.fillColor(C.TEXT).fontSize(20).font('Helvetica-Bold')
     .text(_safe(fw.name), 50, 145);

  doc.fontSize(11).font('Helvetica').fillColor(C.TEXT_MUTED)
     .text(`${_safe(fw.version)}  •  ${_safe(fw.issuer)}`, 50, 170);

  // Metadata box
  doc.rect(50, 195, doc.page.width - 100, 90).fill(C.BG_LIGHT).stroke(C.BORDER);

  const meta = [
    ['Report Reference', _safe(report.reportRef)],
    ['Assessment Period', `${_safe(report.period?.start?.slice(0,10))} to ${_safe(report.period?.end?.slice(0,10))}`],
    ['Generated',        _safe(report.generatedAt?.slice(0,19)) + ' UTC'],
    ['Generated By',     _safe(report.generatedBy)],
  ];
  if (report.tenantId) meta.push(['Tenant', _safe(report.tenantId)]);

  let y = 203;
  for (const [label, val] of meta) {
    doc.fillColor(C.TEXT_MUTED).fontSize(8).font('Helvetica')
       .text(label + ':', 60, y, { continued: true })
       .fillColor(C.TEXT).font('Helvetica').text('  ' + val, { continued: false });
    y += 13;
  }

  // Score and verdict
  const verdictColor = VERDICT_COLOR[verdict] ?? C.FAIL;
  doc.rect(50, 300, doc.page.width - 100, 80).fill(verdictColor).stroke();
  doc.fillColor(C.WHITE).fontSize(36).font('Helvetica-Bold')
     .text(`${score}/100`, 60, 310, { continued: true })
     .fontSize(18).text(`   ${_verdictLabel(verdict)}`, { baseline: 'middle', continued: false });
  doc.fontSize(9).font('Helvetica')
     .text(`Controls: ${report.controlsSummary?.total ?? 0} total | ` +
           `${report.controlsSummary?.pass ?? 0} pass | ` +
           `${report.controlsSummary?.partial ?? 0} partial | ` +
           `${report.controlsSummary?.fail ?? 0} fail`, 60, 350);

  doc.addPage();
}

// ── Executive summary ─────────────────────────────────────────────────────────

function _renderExecutiveSummary(doc, report) {
  _sectionHeader(doc, 'Executive Summary');
  doc.fontSize(9).font('Helvetica').fillColor(C.TEXT)
     .text(_safe(report.executiveSummary), { lineGap: 3 });
  doc.moveDown();
}

// ── Controls table ────────────────────────────────────────────────────────────

function _renderControlsTable(doc, report) {
  _sectionHeader(doc, 'Control Assessments');

  const assessments = report.controlAssessments ?? [];
  if (assessments.length === 0) {
    doc.fontSize(9).text('No control assessments available.'); return;
  }

  const colWidths = [90, 55, 180, 70, 50, 45];
  const headers   = ['Control ID', 'Ref', 'Title', 'Category', 'Status', 'Score'];
  const pageW     = doc.page.width - 100;
  let x           = 50;
  let y           = doc.y;

  // Header row
  doc.rect(50, y, pageW, 16).fill(C.BG_LIGHT).stroke(C.BORDER);
  let cx = x;
  for (let i = 0; i < headers.length; i++) {
    doc.fillColor(C.TEXT).fontSize(7).font('Helvetica-Bold')
       .text(headers[i], cx + 2, y + 3, { width: colWidths[i] - 4, ellipsis: true });
    cx += colWidths[i];
  }
  y += 16;

  for (const a of assessments) {
    if (y > doc.page.height - 80) {
      doc.addPage(); y = 50;
    }
    const rowH = 14;
    doc.rect(50, y, pageW, rowH).stroke(C.BORDER);

    const statusColor = STATUS_COLOR[a.status] ?? C.TEXT;
    cx = 50;
    const cells = [
      { text: _safe(a.controlId), bold: false },
      { text: _safe(a.controlRef), bold: false },
      { text: _safe(a.title), bold: false },
      { text: _safe(a.category), bold: false },
      { text: _safe(a.status), bold: true, color: statusColor },
      { text: `${a.score ?? 0}%`, bold: true,
        color: STATUS_COLOR[a.status] ?? C.TEXT },
    ];

    for (let i = 0; i < cells.length; i++) {
      const cell = cells[i];
      doc.fillColor(cell.color ?? C.TEXT)
         .fontSize(7)
         .font(cell.bold ? 'Helvetica-Bold' : 'Helvetica')
         .text(cell.text, cx + 2, y + 3, { width: colWidths[i] - 4, ellipsis: true });
      cx += colWidths[i];
    }
    y += rowH;
  }

  doc.y = y + 10;
  doc.moveDown();
}

// ── Findings ──────────────────────────────────────────────────────────────────

function _renderFindings(doc, report) {
  const findings = report.findings ?? [];
  _sectionHeader(doc, `Findings (${findings.length})`);

  if (findings.length === 0) {
    doc.fontSize(9).fillColor(C.PASS).text('No findings. All controls pass.').fillColor(C.TEXT);
    doc.moveDown(); return;
  }

  for (const f of findings.slice(0, 50)) {
    if (doc.y > doc.page.height - 100) doc.addPage();
    const sColor = f.severity === 'CRITICAL' ? C.FAIL : C.PARTIAL;
    doc.rect(50, doc.y, doc.page.width - 100, 1).fill(C.BORDER);
    doc.moveDown(0.3);
    doc.fillColor(sColor).fontSize(8).font('Helvetica-Bold')
       .text(`[${_safe(f.severity)}] ${_safe(f.controlId)} — ${_safe(f.description)}`, { continued: false });
    doc.fillColor(C.TEXT).fontSize(8).font('Helvetica')
       .text(`Detail: ${_safe(f.detail)}`);
    if (f.remediation) {
      doc.fillColor(C.TEXT_MUTED).fontSize(7.5)
         .text(`Remediation: ${_safe(f.remediation)}`);
    }
    doc.moveDown(0.5);
  }
}

// ── Evidence summary ──────────────────────────────────────────────────────────

function _renderEvidenceSummary(doc, report) {
  if (doc.y > doc.page.height - 150) doc.addPage();
  _sectionHeader(doc, 'Evidence Summary');

  const ev = report.evidenceSummary ?? {};
  const rows = Object.entries(ev).map(([k, v]) => [
    k.replace(/([A-Z])/g, ' $1').trim(),
    typeof v === 'boolean' ? (v ? 'Yes' : 'No') : String(v),
  ]);

  let y  = doc.y;
  const col1W = 220, col2W = 100;
  for (const [label, val] of rows) {
    if (y > doc.page.height - 60) { doc.addPage(); y = 50; }
    doc.rect(50, y, col1W + col2W, 13).stroke(C.BORDER);
    doc.fillColor(C.TEXT_MUTED).fontSize(7.5).font('Helvetica')
       .text(label, 52, y + 2, { width: col1W - 4 });
    doc.fillColor(C.TEXT).font('Helvetica-Bold')
       .text(val, 52 + col1W, y + 2, { width: col2W - 4 });
    y += 13;
  }
  doc.y = y + 10;
  doc.moveDown();
}

// ── Recommendations ───────────────────────────────────────────────────────────

function _renderRecommendations(doc, report) {
  const recs = report.recommendations ?? [];
  if (recs.length === 0) return;

  if (doc.y > doc.page.height - 120) doc.addPage();
  _sectionHeader(doc, 'Recommendations');

  for (const r of recs.slice(0, 20)) {
    doc.fillColor(C.TEXT).fontSize(8).font('Helvetica-Bold')
       .text(`• [${_safe(r.controlId)}]`, { continued: true })
       .font('Helvetica').text(`  ${_safe(r.action)}`);
    doc.moveDown(0.3);
  }
}

// ── Signature section ─────────────────────────────────────────────────────────

function _renderSignature(doc, report) {
  const sig = report.signature;
  if (!sig) return;

  if (doc.y > doc.page.height - 140) doc.addPage();
  _sectionHeader(doc, 'Cryptographic Signature');

  doc.fontSize(8).font('Helvetica').fillColor(C.TEXT)
     .text('This report is cryptographically signed using Ed25519. Any modification to this ' +
           'document invalidates the signature and will be detected on verification.');

  doc.moveDown(0.5);
  const sigDetails = [
    ['Key ID',     _safe(sig.keyId)],
    ['Algorithm',  _safe(sig.algorithm)],
    ['Signed At',  _safe(sig.signedAt)],
    ['Signer',     _safe(sig.signerId ?? '')],
    ['Report Hash', _safe(report._hash ?? '').slice(0, 32) + '...'],
  ];

  for (const [label, val] of sigDetails) {
    doc.fillColor(C.TEXT_MUTED).font('Helvetica').fontSize(7.5)
       .text(label + ': ', { continued: true })
       .fillColor(C.TEXT).font('Helvetica-Bold').text(val);
  }

  doc.moveDown(0.5);
  doc.fillColor(C.TEXT_MUTED).fontSize(7.5).font('Helvetica')
     .text('Verify via: POST /compliance/report/verify');
}

// ── Page footer ───────────────────────────────────────────────────────────────

function _renderFooter(doc, report) {
  const pages = doc.bufferedPageRange();
  for (let i = pages.start; i < pages.start + pages.count; i++) {
    doc.switchToPage(i);
    const footerY = doc.page.height - 30;
    doc.fillColor(C.TEXT_MUTED).fontSize(7).font('Helvetica')
       .text(
         `QODIQA Compliance Report  •  ${_safe(report.reportRef)}  •  Page ${i + 1} of ${pages.count}`,
         50, footerY, { align: 'center', width: doc.page.width - 100 },
       );
  }
}

// ── Section header helper ─────────────────────────────────────────────────────

function _sectionHeader(doc, title) {
  if (doc.y > doc.page.height - 100) doc.addPage();
  doc.moveDown(0.5);
  doc.rect(50, doc.y, doc.page.width - 100, 20).fill(C.QODIQA_BLUE);
  doc.fillColor(C.WHITE).fontSize(10).font('Helvetica-Bold')
     .text(title, 56, doc.y - 15);
  doc.fillColor(C.TEXT);
  doc.moveDown(0.8);
}

module.exports = { exportPdf };
